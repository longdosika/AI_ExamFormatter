const assert = require('node:assert/strict');
const { score, complete, comparable } = require('./local-vision-metrics.cjs');
const truth = { 1: 'ก', 2: 'ข', 3: null };
assert.deepEqual(score([{id:1,key:'ก'},{id:2,key:'ข'}],truth),{correct:2,wrong:0,missing:0,falsePositive:0,invalid:0,marked:2,recall:1,precision:1});
assert.equal(score([{id:99,key:'ก'},{id:3,key:'ข'}],truth).falsePositive,2);
assert.equal(score([{id:1,key:'ก'},{id:1,key:'ข'}],truth).correct,0);
assert.equal(score([{id:1,key:'ก'},{id:1,key:'ข'}],truth).wrong,2);
assert.equal(score([],truth).missing,2);
assert.equal(score([{id:1,key:'ง'}],truth).precision,0);
assert.equal(score([null,{id:'1',key:'ก'}],truth).invalid,2);
const data={prompt:'same',settings:{seed:7},runtime:{version:'test'},modelIdentity:{name:'test-model',digest:'test-digest'},fixtures:[1,3].map(page=>({page,sha256:'same',truth})),runs:[1,3,1].map(page=>({model:'test-model',page,acceptedScore:score([],truth),rawScore:score([],truth),doneReason:'stop'}))};
data.runs.forEach(run=>{run.sourceSha256='same';run.truth=truth;});
assert.ok(complete(data));assert.ok(comparable([{data},{data}]));
assert.equal(complete({...data,runs:data.runs.slice(0,1)}),false);
assert.equal(complete({...data,runs:data.runs.map(r=>({...r,parseError:'bad'}))}),false);
assert.equal(comparable([{data},{data:{...data,prompt:'different'}}]),false);
for(const change of [{error:'failure'},{doneReason:'length'},{rawScore:{...score([],truth),invalid:1}},{acceptedScore:{}}])assert.equal(complete({...data,runs:data.runs.map(r=>({...r,...change}))}),false);
assert.equal(complete(data,'wrong-model'),false);
assert.equal(comparable([{data},{data:{...data,settings:{seed:8}}}]),false);
assert.equal(comparable([{data},{data:{...data,fixtures:[{page:1,sha256:'other',truth},data.fixtures[1]]}}]),false);
console.log('Local vision evaluator: correct, wrong, abstention, unknown ids and duplicates passed');
const roi={...data,fixtures:data.fixtures.map((f,i)=>({...f,page:1,caseId:'q'+i})),runs:data.runs.map((r,i)=>({...r,page:1,caseId:'q'+(i%2)}))};
assert.ok(complete(roi));
assert.equal(complete({...roi,runs:roi.runs.map(r=>({...r,caseId:'wrong'}))}),false);
assert.equal(complete({...roi,runs:roi.runs.map(r=>({...r,sourceSha256:'stale'}))}),false);
assert.equal(complete({...roi,runs:roi.runs.map(r=>({...r,truth:{1:'ง'}}))}),false);
